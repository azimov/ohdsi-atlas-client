#!/usr/bin/env python3
"""Publish R vignettes as pages of the shared documentation site.

The R vignettes are the single source of truth for R guidance. This copies
their Markdown body into ``docs/`` so the mkdocs site can link to it, instead
of maintaining a second hand-written copy that drifts.

Usage::

    python scripts/sync_vignettes.py           # regenerate docs/*.md
    python scripts/sync_vignettes.py --check   # fail if out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VIGNETTES = ROOT / "OhdsiAtlasClient" / "vignettes"
DOCS = ROOT / "docs"

# vignette stem -> (published filename, site title)
PUBLISHED: dict[str, tuple[str, str]] = {
    "migrating-from-rohdsiwebapi": (
        "migrating-from-rohdsiwebapi.md",
        "R: migrating from ROhdsiWebApi",
    ),
}

BANNER = (
    "<!-- Generated by scripts/sync_vignettes.py from "
    "OhdsiAtlasClient/vignettes/{stem}.Rmd. Do not edit by hand. -->\n\n"
    "> This page is the R vignette "
    "`vignette(\"{stem}\", package = \"OhdsiAtlasClient\")` published on the site. "
    "Code blocks are not executed here; see the vignette for rendered output.\n"
)


def convert(stem: str) -> str:
    text = (VIGNETTES / f"{stem}.Rmd").read_text(encoding="utf-8")
    # Drop the YAML header.
    text = re.sub(r"\A---\n.*?\n---\n", "", text, count=1, flags=re.DOTALL)
    # Drop setup chunks that are hidden in the rendered vignette.
    text = re.sub(
        r"^```\{r[^}]*include\s*=\s*FALSE[^}]*\}\n.*?^```\s*$\n?",
        "",
        text,
        flags=re.MULTILINE | re.DOTALL,
    )
    # `<a id="...">` is not valid Markdown; drop it and keep the heading.
    text = re.sub(r"\n<a id=\"([^\"]+)\"></a>\n", r"\n", text)
    # R chunk options like ```{r, eval = FALSE} -> fenced R blocks.
    text = re.sub(r"^```\{r[^}]*\}\s*$", "```r", text, flags=re.MULTILINE)
    filename, _ = PUBLISHED[stem]
    banner = BANNER.format(stem=stem)
    return banner + "\n" + text.lstrip("\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    failures: list[str] = []
    for stem, (filename, _) in PUBLISHED.items():
        if not (VIGNETTES / f"{stem}.Rmd").exists():
            failures.append(f"missing vignette OhdsiAtlasClient/vignettes/{stem}.Rmd")
            continue
        document = convert(stem)
        target = DOCS / filename
        if args.check:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != document:
                failures.append(
                    f"docs/{filename} is out of date; run "
                    "python scripts/sync_vignettes.py"
                )
        else:
            target.write_text(document, encoding="utf-8")
            print(f"Wrote docs/{filename}")

    if failures:
        for failure in failures:
            print(failure, file=sys.stderr)
        return 1
    if args.check:
        print("vignette pages are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
